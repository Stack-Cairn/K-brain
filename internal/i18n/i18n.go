package i18n

const English = "en"
const Chinese = "zh_cn"

func Valid(language string) bool { return language == English || language == Chinese }
func Normalize(language string) string {
	if language == Chinese {
		return Chinese
	}
	return English
}
func Text(language, text string) string {
	if Normalize(language) == Chinese {
		if translated, ok := chinese[text]; ok {
			return translated
		}
	}
	return text
}

