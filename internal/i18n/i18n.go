package i18n

const English = "en"
const Chinese = "zh_cn"
const TraditionalChinese = "zh_Hant"

func Valid(language string) bool {
	return language == English || language == Chinese || language == TraditionalChinese
}
func Normalize(language string) string {
	if language == TraditionalChinese {
		return TraditionalChinese
	}
	if language == Chinese {
		return Chinese
	}
	return English
}
func Text(language, text string) string {
	if language == TraditionalChinese {
		if translated, ok := traditionalChinese[text]; ok {
			return translated
		}
		if translated, ok := chinese[text]; ok {
			return translated
		}
	}
	if Normalize(language) == Chinese {
		if translated, ok := chinese[text]; ok {
			return translated
		}
	}
	return text
}

